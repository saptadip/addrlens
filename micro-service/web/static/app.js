// Tooltip portal: when an <details class="info-tip"> opens, move its
// .info-body out of the details and into <body> with position:fixed. This
// escapes every ancestor stacking context — .cell creates one via its
// entry-animation transform, so a z-index:30 tooltip nested inside would
// otherwise be painted below the next sibling card. The tooltip is also
// flipped upward when there's more room above the ⓘ, and its max-height
// is capped to the actual free space so long content scrolls inside the
// tooltip, not off the page.
function _reposTooltip(det){
  const body = det._portaledBody;
  if(!body) return;
  const sum = det.querySelector('summary').getBoundingClientRect();
  const spaceBelow = window.innerHeight - sum.bottom - 12;
  const spaceAbove = sum.top - 12;
  const needed = body.scrollHeight;
  body.style.position = 'fixed';
  body.style.left = 'auto';
  body.style.right = (window.innerWidth - sum.right) + 'px';
  body.style.zIndex = '9999';
  if(needed > spaceBelow && spaceAbove > spaceBelow){
    body.style.top = 'auto';
    body.style.bottom = (window.innerHeight - sum.top + 6) + 'px';
    body.style.maxHeight = (spaceAbove - 6) + 'px';
  } else {
    body.style.top = (sum.bottom + 6) + 'px';
    body.style.bottom = 'auto';
    body.style.maxHeight = (spaceBelow - 6) + 'px';
  }
}
document.addEventListener('toggle', (e) => {
  const det = e.target;
  if(!det.classList || !det.classList.contains('info-tip')) return;
  if(det.open){
    // Close any other open tooltip first — one open at a time keeps the
    // portal cleanup deterministic and matches expected popover UX.
    document.querySelectorAll('details.info-tip[open]').forEach(other => {
      if(other !== det) other.open = false;
    });
    const body = det.querySelector('.info-body');
    if(body){
      document.body.appendChild(body);
      det._portaledBody = body;
    }
    _reposTooltip(det);
  } else if(det._portaledBody){
    const b = det._portaledBody;
    b.removeAttribute('style');       // reset inline positioning
    if(det.isConnected) det.appendChild(b);   // put it back inside the <details>
    else b.remove();                          // details already gone (re-render) → drop the orphan
    det._portaledBody = null;
  }
}, true);
// Safety net: any orphaned .info-body left in <body> from a previous render is
// dropped as soon as a fresh lookup starts.
function dropOrphanTooltips(){
  document.body.querySelectorAll(':scope > .info-body').forEach(b => b.remove());
}
