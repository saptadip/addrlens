// -- Life Mode state management (Task 9) ------------------------------------
// renderAllPanels: called by setLifeMode() on every toggle.
// Single-address view: eduData holds the full /api/lookup response.
// When Life Mode is ON, render the lens view in place of the raw tabs.
function renderAllPanels() {
  const onLife = document.body.classList.contains('life-mode');
  let lensEl = document.getElementById('lens-view');
  if (!lensEl) {
    // Lazy-create the lens container once, inserted after the panels block.
    lensEl = document.createElement('div');
    lensEl.id = 'lens-view';
    // Insert after the last panel section inside #view-main.
    const panelConn = document.getElementById('panel-conn');
    if (panelConn && panelConn.parentNode) {
      panelConn.parentNode.insertBefore(lensEl, panelConn.nextSibling);
    } else {
      const viewMain = document.getElementById('view-main');
      if (viewMain) viewMain.appendChild(lensEl);
    }
  }
  // Spec D: sweep any tooltip popovers still portaled from an earlier render
  if (typeof dropOrphanTooltips === 'function') dropOrphanTooltips();
  if (onLife) {
    // Render the lens grid if data is loaded.
    lensEl.innerHTML = eduData ? renderLensSingle(eduData) : '';
    // Spec D Task 8: initialize lens map after HTML is in the DOM.
    // Skip when the lens rendered an error placeholder with no #lens-map.
    if (eduData && eduData.address && document.getElementById('lens-map')) {
      initLensMap(eduData.address);
    }
  } else {
    if (lensMap) {
      try { lensMap.remove(); } catch (e) {}
      lensMap = null;
      lensAddressMarker = null;
      lensMapFeaturePins = [];
    }
    lensEl.innerHTML = '';
  }
  // Disable the Life Mode toggle iff BOTH lenses are unavailable for the
  // focused address (single-address view uses eduData as the focused addr).
  const toggle = document.getElementById('life-mode-toggle');
  if (toggle) {
    const focused = eduData || null;
    if (focused && !isAnyLensAvailable(focused)) {
      toggle.setAttribute('disabled', 'true');
      toggle.setAttribute('title', 'Lens unavailable for this address');
    } else {
      toggle.removeAttribute('disabled');
      toggle.removeAttribute('title');
    }
  }
}

function setLifeMode(on) {
  const btn = document.getElementById('life-mode-toggle');
  document.body.classList.toggle('life-mode', on);
  // Visual ON state lives on the switch (.lm-toggle.on), not on the whole
  // button. Label stays "Life Lens" — no dynamic text swap.
  btn.classList.toggle('on', on);
  btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  btn.setAttribute('aria-label', on
    ? 'Life Lens on (toggle to switch off)'
    : 'Life Lens off (toggle to switch on)');
  try { localStorage.setItem(LM_STATE_KEY, on ? 'on' : 'off'); } catch (e) {}
  // Spec D: sweep any lingering modal/tooltip state on mode switch
  const modal = document.getElementById('lens-modal');
  if (modal && !modal.hidden) closeLensModal();
  if (typeof dropOrphanTooltips === 'function') dropOrphanTooltips();
  renderAllPanels();   // no HTTP call; data already cached per address
  // If the compare view is open, re-render it too (Life Mode forks the output).
  if (location.hash === '#compare') renderCompare();
}

function initLifeMode() {
  const btn = document.getElementById('life-mode-toggle');
  if (!btn) return;

  // Sticky state.
  let saved = null;
  try { saved = localStorage.getItem(LM_STATE_KEY); } catch (e) {}
  setLifeMode(saved === 'on');

  // First-visit pulse.
  let seen = null;
  try { seen = localStorage.getItem(LM_SEEN_KEY); } catch (e) {}
  const stopPulse = () => {
    btn.classList.remove('pulse');
    try { localStorage.setItem(LM_SEEN_KEY, '1'); } catch (e) {}
  };
  if (!seen) {
    btn.classList.add('pulse');
    setTimeout(stopPulse, LM_PULSE_MS);
  }

  btn.addEventListener('click', () => {
    stopPulse();                                                          // any click stops the pulse
    setLifeMode(!document.body.classList.contains('life-mode'));
  });

  // Delegate picker clicks. One handler covers picker instances rendered
  // in either the single-address view or the compare view.
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lens-picker [data-lens]');
    if (btn) setActiveLens(btn.dataset.lens);
  });
}

