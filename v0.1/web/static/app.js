let amenFetching=false, amenAttempts=0;
async function fetchAmenities(lat,lon,isRetry){
  if(amenFetching) return;
  amenFetching=true;
  if(!isRetry) amenAttempts=0;
  amenAttempts++;
  const loading=`<div class="loading"><span class="spinner"></span> Reading Berlin Open Data + OpenStreetMap${isRetry?' (retrying)':''}…</div>`;
  $amen.innerHTML=loading; $med.innerHTML=loading;
  try{
    const r=await fetch(`/api/amenities?lat=${lat}&lon=${lon}`);
    const d=await r.json();
    if(!r.ok){
      const err=`<div class="error">${esc(d.error||'Failed to load amenities.')}</div>`;
      $amen.innerHTML=err; $med.innerHTML=err; return;
    }
    renderAmenities(d);
    $amen.dataset.loaded='1'; $med.dataset.loaded='1';
    refreshSaveBtn();
    // ponytail: Overpass throttles per-IP; a fresh call 3 s later usually
    // clears it. One silent retry, then accept whatever we have.
    if(!isRetry && amenHasErrors()){
      setTimeout(()=>{ if(lastCoord && lat===lastCoord.lat && lon===lastCoord.lon) fetchAmenities(lat,lon,true); else refreshSaveBtn(); }, 3000);
    }
  }catch(e){
    const err=`<div class="error">Network error: ${esc(e.message)}</div>`;
    $amen.innerHTML=err; $med.innerHTML=err;
  }
  finally{amenFetching=false; refreshSaveBtn();}
}

